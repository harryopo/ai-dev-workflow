#!/usr/bin/env python3
"""Skill integrity gate: broken links, orphans, and unsourced counts.

Usage:
    python scripts/audit_integrity.py [--skill-dir PATH] [--json]

Exit codes: 0 = all checks pass, 1 = findings present, 2 = bad invocation.
Only checks resources the skill actually ships; unknown CLI flags abort rather
than silently scanning nothing.
"""

import argparse
import json
import re
import sys
from pathlib import Path

# Windows 下 stdout 默认 gbk，中文结论会变乱码，门禁输出统一强制 UTF-8
for _s in (sys.stdout, sys.stderr):
    if hasattr(_s, "reconfigure"):
        _s.reconfigure(encoding="utf-8")

# Resource dirs whose files must be referenced somewhere, and whose internal
# paths mentioned in markdown must resolve to real files.
RESOURCE_DIRS = ("references", "subskills", "templates", "themes", "scripts", "rules", "tests")
# generated by running the tools themselves; never meant to be referenced or shipped
SKIP_DIR_NAMES = {"__pycache__", ".pytest_cache", "node_modules"}

# file -> (regex matching one item, label of what is being counted)
# Each rule was validated against the shipped file, not a synthetic sample.
COUNT_RULES = {
    "references/palettes.md": (r"(?m)^### P-\d{3}:", "palettes"),
    "references/font-pairings.md": (r"(?m)^### FP-\d{3}:", "font pairings"),
    "references/slop-test.md": (r"(?m)^### V\d+\.", "slop tests"),
    "references/anti-ai-slop.md": (r"(?m)^### \d+\.", "anti-slop rules"),
    "references/premium-design-rules.md": (r"(?m)^## \d+\.", "premium rules"),
    "references/ux-guidelines.md": (r"(?m)^### ", "ux guidelines"),
    "references/macrostructures.md": (r"(?m)^### ", "macrostructures"),
    "references/themes.md": (r"(?m)^### ", "themes"),
    "references/brand-personality-expanded.md": (r"(?m)^### ", "brand personalities"),
    "references/chart-types.md": (r"(?m)^## \d+\.", "chart types"),
}

# Exact-number declarations only; "50+" style claims carry no checkable value.
EXACT_NUMBER_IN_TITLE = re.compile(r"^#\s+.*?(\d+)\s*(?:\u4e2a|\u6761|\u79cd|P|_)", re.M)

SUBSKILL_CLAIMS = [
    (
        "subskills/critique/SKILL.md",
        r"(\d+)\s*\u6761(?:\u786e\u5b9a\u6027)?\u63a2\u6d4b\u5668",
        r"(?m)^\|\s*(?:V|R|I)\d+\s*\|",
        "critique detector rules",
    ),
    (
        "subskills/review/SKILL.md",
        r"(\d+)\s*(?:\u4e2a)?\s*\u7ef4\u5ea6",
        r"(?m)^####\s+2\.\d+\s",
        "review dimensions",
    ),
]

# Headings of the form '## Part 7: 技术栈（10 栈）' promise a count that the
# numbered '###' sections underneath must match.
PART_CLAIM = re.compile(r"(?m)^(#{2,3}) [^\n]*?（(\d+)\s*(\u6808|\u7ef4\u5ea6|\u7c7b\u578b|\u914d\u5bf9|\u8c03\u8272\u677f)")

TOOL_WORDS = {
    "AskUserQuestion", "WebSearch", "WebFetch", "Read", "Write", "Edit",
    "Glob", "Grep", "Bash", "Task", "TodoWrite",
}


class Findings:
    def __init__(self):
        self.items = []
        self.passed = []

    def fail(self, check, detail):
        self.items.append({"check": check, "detail": detail})

    def ok(self, check, detail):
        self.passed.append({"check": check, "detail": detail})


def markdown_files(root):
    return sorted(p for p in root.rglob("*.md") if p.is_file())


def read(path):
    return path.read_text(encoding="utf-8", errors="replace")


FENCE_DELIM = re.compile(r"^[ \t]*```[ \t]*[\w/+.\-]*[ \t]*$")


def strip_code_fences(text):
    """Not used for reference scanning (see check_paths); kept for report bodies."""
    out, inside = [], False
    for line in text.splitlines():
        if FENCE_DELIM.match(line):
            inside = not inside
            continue
        if not inside:
            out.append(line)
    return "\n".join(out)


def exact_title_count(title):
    """Return the count a title claims, or None when the claim is not exact.

    '50+ 风格' and '（8 → 14）' are ranges/arrows, not checkable numbers.
    """
    if "\u2192" in title or "->" in title:
        return None
    m = re.search(r"(\d+)\s*\+?", title)
    if not m:
        return None
    if m.group(0).rstrip().endswith("+"):
        return None
    return int(m.group(1))


def check_paths(root, f):
    """Every resource path named in any markdown file must exist.

    Scans raw text: a path inside an example block should still resolve.
    """
    total = 0
    for md in markdown_files(root):
        text = read(md)
        for ref in set(re.findall(
                r"(?<![\w./])((?:%s)/[A-Za-z0-9_.\-/]+)" % "|".join(RESOURCE_DIRS),
                text)):
            total += 1
            if not (root / ref).exists():
                f.fail("broken-reference", "%s -> %s" % (md.relative_to(root), ref))
    if total:
        f.ok("broken-reference", "%d path references resolve" % total)


def check_orphans(root, f):
    """Every shipped resource file must be referenced by some markdown file."""
    corpus = "\n".join(read(md) for md in markdown_files(root))
    orphans = []
    for d in RESOURCE_DIRS:
        base = root / d
        if not base.is_dir():
            continue
        for p in sorted(base.rglob("*")):
            if not p.is_file():
                continue
            rel = p.relative_to(root).as_posix()
            if SKIP_DIR_NAMES & set(p.relative_to(root).parts):
                continue
            if p.suffix.lower() == ".md" and rel.endswith("SKILL.md"):
                continue
            if rel not in corpus:
                orphans.append(rel)
    for o in orphans:
        f.fail("orphan-resource", "%s is never referenced by any markdown file" % o)
    if not orphans:
        f.ok("orphan-resource", "no unreferenced resources")


def check_counts(root, f):
    for rel, (pattern, label) in COUNT_RULES.items():
        path = root / rel
        if not path.exists():
            continue
        body = strip_code_fences(read(path))
        actual = len(re.findall(pattern, body))
        title = read(path).splitlines()[0]
        declared = exact_title_count(title)
        if declared is None:
            f.ok("declared-count", "%s: title makes no exact claim" % rel)
            continue
        if declared != actual:
            f.fail("declared-count",
                   "%s declares %d %s, file contains %d" % (rel, declared, label, actual))
        else:
            f.ok("declared-count", "%s: %d %s verified" % (rel, declared, label))


def check_subskill_claims(root, f):
    for rel, claim_rx, item_rx, label in SUBSKILL_CLAIMS:
        path = root / rel
        if not path.exists():
            continue
        body = strip_code_fences(read(path))
        claims = {int(n) for n in re.findall(claim_rx, body)}
        actual = len(re.findall(item_rx, body))
        if not claims:
            f.fail("subskill-claim", "%s: no '%s' claim found to verify" % (rel, label))
        elif claims != {actual}:
            f.fail("subskill-claim",
                   "%s claims %s %s, file lists %d" % (rel, sorted(claims), label, actual))
        else:
            f.ok("subskill-claim", "%s: %d %s verified" % (rel, actual, label))


def check_index_numbers(root, f):
    """Numbers in the SKILL.md resource index must match the file's own title."""
    skill = root / "SKILL.md"
    if not skill.exists():
        return
    listed = set()
    for line in read(skill).splitlines():
        m = re.match(r"\|\s*((?:references|templates|themes)/\S+?)\s*\|\s*(\d+)\s", line)
        if not m:
            continue
        rel, num = m.group(1), int(m.group(2))
        listed.add(rel)
        target = root / rel
        if not target.exists():
            f.fail("index-missing", "index lists %s but file is absent" % rel)
            continue
        declared = exact_title_count(read(target).splitlines()[0])
        if declared is None:
            f.ok("index-count", "index %s: file title makes no exact claim" % rel)
        elif declared != num:
            f.fail("index-count",
                   "index says %d for %s, its title says %d" % (num, rel, declared))
        else:
            f.ok("index-count", "index %d matches %s" % (num, rel))
    for rel in sorted(listed):
        if not (root / rel).exists():
            f.fail("index-missing", "index lists %s but file is absent" % rel)


def check_index_completeness(root, f):
    """Every file under references/ must be listed in the SKILL.md index."""
    skill = root / "SKILL.md"
    if not skill.exists():
        return
    text = read(skill)
    base = root / "references"
    if not base.is_dir():
        return
    for p in sorted(base.glob("*.md")):
        rel = "references/%s" % p.name
        if rel not in text:
            f.fail("index-omission", "%s exists but is not listed in the SKILL.md index" % rel)



def check_cross_claims(root, f):
    """Counts of a shared dataset quoted anywhere in the skill must match the data.

    '56条Slop Test' is quoted in SKILL.md, review, critique, refine, README and the
    prompt templates; updating only some of them leaves the skill quoting its own
    numbers inconsistently. Every markdown file is scanned (release notes excepted —
    they are a version log and rewriting a past entry would falsify it).
    """
    slop = root / "references" / "slop-test.md"
    if not slop.exists():
        return
    actual = len(re.findall(r"(?m)^### V\d+\.", strip_code_fences(read(slop))))
    stale = []
    # 数字必须与"Slop Test"相邻，否则同一行里的"26条确定性探测器""16条规则"会被误抓
    ADJACENT = [re.compile(r"(?i)(\d+)\s*(?:条|项)[^|，。；\n]{0,12}?slop[ -]?test"),
                re.compile(r"(?i)slop[ -]?test[^|，。；\n]{0,10}?(\d+)\s*(?:条|项)")]
    for md in markdown_files(root):
        if md.relative_to(root).as_posix() in ("RELEASE-NOTES.md",):
            continue
        for lineno, line in enumerate(read(md).splitlines(), 1):
            for pat in ADJACENT:
                for num in pat.findall(line):
                    if int(num) != actual:
                        stale.append("%s:%s 写 %s 条" % (md.relative_to(root).as_posix(), lineno, num))
    if stale:
        f.fail("cross-claim", "slop-test.md 实为 %d 条但 %s" % (actual, "; ".join(sorted(set(stale)))))
    else:
        f.ok("cross-claim", "all Slop Test quotes match %d items" % actual)

    table = root / "rules" / "slop-table.json"
    if table.is_file():
        n = len(json.loads(table.read_bytes().decode("utf-8"))["rules"])
        wrong = []
        for md in markdown_files(root):
            for lineno, line in enumerate(read(md).splitlines(), 1):
                if "slop_scan" not in line and "slop-table" not in line:
                    continue
                for m in re.finditer(r"(\d+)\s*条(?:静态)?规则", line):
                    if int(m.group(1)) != n:
                        wrong.append("%s:%s 写 %s 条" % (md.relative_to(root).as_posix(), lineno, m.group(1)))
        if wrong:
            f.fail("cross-claim", "rules/slop-table.json 有 %d 条但 %s" % (n, "; ".join(wrong)))
        else:
            f.ok("cross-claim", "slop-table quotes match its %d rules" % n)


def check_denominators(root, f):
    """Total-count denominators inside a dataset file must match its item count.

    Renumbering a checklist leaves stale 'X/57' rows in the scoring table and
    report examples; those silently keep the old total alive.
    """
    for rel, (pattern, label) in COUNT_RULES.items():
        path = root / rel
        if not path.exists():
            continue
        actual = len(re.findall(pattern, strip_code_fences(read(path))))
        # the 0-100 score scale is a legitimate second denominator; values above
        # 200 are pixel lists (e.g. breakpoints 320/375/414/768), not totals
        allowed = {actual, 100}
        bad = set()
        for num, den in re.findall(r"(?m)^.*?(\d+)\s*/\s*(\d+)", read(path)):
            d = int(den)
            if 10 <= d <= 200 and d not in allowed and int(num) <= d:
                bad.add(d)
        for d in sorted(bad):
            f.fail("stale-total", "%s still uses /%d as the total, but has %d %s"
                   % (rel, d, actual, label))
        if not bad:
            f.ok("stale-total", "%s totals match %d %s" % (rel, actual, label))


def check_part_claims(root, f):
    """'Part N: X（M 栈）' headings must match the sections actually written."""
    hits = 0
    for md in instruction_files(root):
        if not md.exists():
            continue
        lines = strip_code_fences(read(md)).splitlines()
        for i, line in enumerate(lines):
            m = PART_CLAIM.match(line)
            if not m:
                continue
            level, claimed = len(m.group(1)), int(m.group(2))
            sub_level = "#" * (level + 1)
            body = []
            for nxt in lines[i + 1:]:
                if nxt.startswith("#" * level + " "):
                    break
                if nxt.startswith(sub_level + " "):
                    body.append(nxt)
            counted = [b for b in body if re.match(r"^#{%d}\s+\d+\." % (level + 1), b)]
            if not counted:
                continue
            hits += 1
            if len(counted) != claimed:
                f.fail("part-claim", "%s: '%s' promises %d, %d sections written"
                       % (md.relative_to(root), line.strip()[:46], claimed, len(counted)))
    if not hits:
        f.ok("part-claim", "no parenthesised section claims")


def check_fences(root, f):
    """Code fences must balance, and no fence may open or close mid-line.

    An unbalanced fence makes every heading/table after it render as code, which
    silently breaks any tool that parses the document by structure.
    """
    bad = 0
    for md in markdown_files(root):
        lines = read(md).splitlines()
        inside = False
        inline_hits = []
        for i, line in enumerate(lines, 1):
            if FENCE_DELIM.match(line):
                inside = not inside
            elif "```" in line:
                inline_hits.append((i, line.strip()[:60]))
        rel = str(md.relative_to(root))
        if inside:
            f.fail("fence-unbalanced", "%s ends inside an open code fence" % rel)
            bad += 1
        for i, snippet in inline_hits:
            f.fail("fence-inline", "%s:%d has a fence marker mid-line: %s" % (rel, i, snippet))
            bad += 1
    if not bad:
        f.ok("fence-unbalanced", "all code fences balanced")


def check_frontmatter(root, f):
    text = read(root / "SKILL.md")
    m = re.match(r"\A---\n(.*?)\n---\n", text, re.S)
    if not m:
        f.fail("frontmatter", "SKILL.md has no parseable YAML frontmatter")
        return
    block = m.group(1)
    name = re.search(r"^name:\s*(.+)$", block, re.M)
    if not name or not re.fullmatch(r"[A-Za-z0-9-]+", name.group(1).strip()):
        f.fail("frontmatter", "name must be letters/digits/hyphens only")
    else:
        f.ok("frontmatter", "name '%s' valid" % name.group(1).strip())
    if len(block) > 1024:
        f.fail("frontmatter", "frontmatter is %d chars, spec limit 1024" % len(block))
    else:
        f.ok("frontmatter", "%d chars, within 1024" % len(block))
    desc = re.search(r"^description:\s*(.+)$", block, re.M)
    if desc and len(desc.group(1)) > 1024:
        f.fail("frontmatter", "description is %d chars" % len(desc.group(1)))


def instruction_files(root):
    return [root / "SKILL.md"] + sorted((root / "subskills").glob("*/SKILL.md"))


def check_round_consistency(root, f):
    """Total-round claims must equal the number of round sections actually written.

    A stale 'N 轮' in the intro makes an agent stop the interview early, which is
    the failure this skill exists to prevent. Ordinals ('第 4 轮') and minimums
    ('至少 1 轮') are not totals and are ignored.
    """
    research = root / "subskills" / "research" / "SKILL.md"
    if not research.exists():
        f.ok("round-count", "no research subskill, skipped")
        return
    actual = len(re.findall(r"(?m)^###\s*第\s*(\d+)\s*轮", read(research)))
    if not actual:
        f.fail("round-count", "research subskill has no '### 第 N 轮' sections to count")
        return
    claims = {}
    for md in instruction_files(root):
        if not md.exists():
            continue
        text = strip_code_fences(read(md))
        for m in re.finditer(r"(\d+)\s*轮", text):
            before = text[max(0, m.start() - 10):m.start()]
            after = text[m.end():m.end() + 14]
            if re.search(r"至少|最少|第\s*$|\d-\d$|[\d\-–]$", before):
                continue
            if not re.search(r"调研|对话|AskUserQuestion|\*\*", after):
                continue
            claims.setdefault(int(m.group(1)), []).append(
                "%s:%s" % (md.relative_to(root), before[-8:].replace("\n", " ") + m.group(0)))
    wrong = {k: v for k, v in claims.items() if k != actual}
    if wrong:
        for k in sorted(wrong):
            f.fail("round-count",
                   "%d \u8f6e claimed but research writes %d rounds -> %s"
                   % (k, actual, "; ".join(wrong[k][:4])))
    else:
        f.ok("round-count", "%d round claims match %d written rounds" % (len(claims), actual))


def check_tools(root, f):
    text = read(root / "SKILL.md")
    allowed = set()
    m = re.search(r"^allowed-tools:\s*(.+)$", text, re.M)
    if m:
        allowed = {t.strip() for t in m.group(1).split(",")}
    used = {t for t in TOOL_WORDS if re.search(r"\b%s\b" % t, strip_code_fences(text))}
    missing = sorted(used - allowed)
    if missing:
        f.fail("allowed-tools", "SKILL.md names tools not in allowed-tools: %s" % ", ".join(missing))
    else:
        f.ok("allowed-tools", "all mentioned tools are allowed")


def check_policy_consistency(root, f):
    """One policy may carry only one number; rules/policy.json is the single source.

    Both directions are compared: machine thresholds (rules/slop-table.json,
    scripts/render_probe.py) must equal the policy value, and every prose statement
    of the policy must carry a number the policy allows. Each policy also declares how
    many prose hits its patterns must find — when wording drifts so far that patterns
    stop matching, coverage collapses and that is reported instead of a silent pass.
    """
    policy_path = root / "rules" / "policy.json"
    if not policy_path.is_file():
        f.fail("policy-consistency", "rules/policy.json 不存在，政策数字无处对账")
        return
    policies = json.loads(policy_path.read_bytes().decode("utf-8"))["policies"]
    table_path = root / "rules" / "slop-table.json"
    rules = {}
    if table_path.is_file():
        rules = {r["id"]: r for r in json.loads(table_path.read_bytes().decode("utf-8"))["rules"]}
    probe_path = root / "scripts" / "render_probe.py"
    probe_text = read(probe_path) if probe_path.exists() else ""

    problems = []
    hits_total = 0
    for p in policies:
        allowed = {float(p["value"])} | {float(x) for x in p.get("also_allowed", [])}
        for rid in p.get("rule_ids", []):
            rule = rules.get(rid)
            if rule is None:
                problems.append("%s: 判定表里没有规则 %s" % (p["id"], rid))
                continue
            try:
                thr = float(rule.get("threshold"))
            except (TypeError, ValueError):
                problems.append("%s: 规则 %s 没有可比对的 threshold" % (p["id"], rid))
                continue
            if thr not in allowed:
                problems.append("%s: slop-table %s threshold=%s 不在政策允许值 %s 内"
                                % (p["id"], rid, rule.get("threshold"), sorted(allowed)))
        for key, val in (p.get("probe") or {}).items():
            if not probe_text:
                problems.append("%s: 找不到 scripts/render_probe.py，无法核对 %s" % (p["id"], key))
            elif re.search(r"(?<![\d.])%s(?![\d])" % re.escape(str(val)), probe_text) is None:
                problems.append("%s: render_probe.py 里找不到 %s=%s" % (p["id"], key, val))
        if p.get("probe_source"):
            src = root / p["probe_source"]
            if not src.is_file():
                problems.append("%s: 声明的读取方不存在：%s" % (p["id"], p["probe_source"]))
            elif "policy.json" not in read(src):
                problems.append("%s: %s 必须从 rules/policy.json 取阈值，不能把数字抄第二份"
                                % (p["id"], p["probe_source"]))

        prose = p.get("prose") or {}
        patterns = [re.compile(x) for x in prose.get("patterns", [])]
        excludes = prose.get("exclude", [])
        min_hits = prose.get("min_hits", 1)
        hits = 0
        seen = set()
        for md in markdown_files(root):
            # 发布记录是历史陈述，允许引用当时的数字；政策冲突只比对规范文档
            if md.relative_to(root).as_posix() in ("RELEASE-NOTES.md",):
                continue
            for lineno, line in enumerate(read(md).splitlines(), 1):
                if not line.strip() or any(x in line for x in excludes):
                    continue
                for pat in patterns:
                    for m in pat.finditer(line):
                        try:
                            val = float(m.group(1))
                        except (IndexError, TypeError, ValueError):
                            continue
                        # 两个方向的模式会命中同一个数字，按"处"计数而不是按"次匹配"
                        if (md, lineno, val) in seen:
                            continue
                        seen.add((md, lineno, val))
                        hits += 1
                        if val not in allowed:
                            problems.append("%s: 文档写 %g（政策允许 %s）@ %s:%s ｜ %s"
                                            % (p["id"], val, sorted(allowed),
                                               md.relative_to(root).as_posix(), lineno,
                                               line.strip()[:70]))
        if hits < min_hits:
            problems.append("%s: 只匹配到 %d 处政策措辞（应 ≥%d）——措辞已漂移，对账覆盖不足"
                            % (p["id"], hits, min_hits))
        hits_total += hits

    if problems:
        for x in problems:
            f.fail("policy-consistency", x)
    else:
        f.ok("policy-consistency", "%d 条政策与 %d 处文档措辞、判定表阈值双向一致"
             % (len(policies), hits_total))


def check_gate_inventory(root, f):
    """Every delivery gate must be registered, exist, be indexed, and be counted right.

    An unregistered check drifts out of the delivery flow silently; a stale
    'N 道门禁' in SKILL.md makes the agent stop running gates one too early.
    """
    gf = root / "rules" / "gates.json"
    if not gf.is_file():
        f.fail("gate-inventory", "rules/gates.json 不存在，门禁清单没有真值源")
        return
    gates = json.loads(gf.read_bytes().decode("utf-8"))["gates"]
    registered = {g["script"] for g in gates}
    mds = markdown_files(root)
    indexed = set()
    for md in mds:
        for m in re.finditer(r"scripts/[\w.-]+\.(?:py|mjs)", read(md)):
            indexed.add(m.group(0))

    problems = []
    for g in gates:
        if not (root / g["script"]).is_file():
            problems.append("%s 指向的脚本不存在：%s" % (g["id"], g["script"]))
        if g["script"] not in indexed:
            problems.append("%s 的脚本没被任何 markdown 索引：%s" % (g["id"], g["script"]))
    unlisted = []
    for rel in sorted(indexed - registered):
        for md in mds:
            if any(rel in line and "门禁" in line for line in read(md).splitlines()):
                unlisted.append("%s（见 %s）" % (rel, md.relative_to(root).as_posix()))
                break
    if unlisted:
        problems.append("文档里称作门禁但没登记进 rules/gates.json：%s" % "; ".join(unlisted))

    claims = {}
    cn = {"一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6, "七": 7, "八": 8, "九": 9, "十": 10}
    for md in [root / "SKILL.md", root / "subskills" / "review" / "SKILL.md"]:
        if not md.exists():
            continue
        for m in re.finditer(r"([一二三四五六七八九十]|\d+)\s*道门禁", strip_code_fences(read(md))):
            tok = m.group(1)
            n = int(tok) if tok.isdigit() else cn[tok]
            claims.setdefault(n, []).append(md.relative_to(root).as_posix())
    for n, where in sorted(claims.items()):
        if n != len(gates):
            problems.append("文档写 %d 道门禁（%s），清单里实际 %d 道"
                            % (n, ", ".join(sorted(set(where))), len(gates)))
    if not claims:
        problems.append("SKILL.md / review 里没有任何「N 道门禁」的数量声明，清单无人对账")

    if problems:
        for p in problems:
            f.fail("gate-inventory", p)
    else:
        f.ok("gate-inventory", "%d 道门禁都存在、已索引，数量声明一致" % len(gates))


def check_layer_sum(root, f):
    """The review report template's per-layer counts must add up to its own total.

    The 56-item checklist is presented to the reviewer as a scored table; when a
    layer is dropped or renumbered, the printed total stops matching the rows above
    it and the score becomes unfalsifiable. Rows scored as '—' (the pre-emit axes,
    scored out of 30 separately) carry no checklist item and are excluded.
    """
    review = root / "subskills" / "review" / "SKILL.md"
    slop = root / "references" / "slop-test.md"
    if not (review.exists() and slop.exists()):
        f.ok("layer-sum", "no review report template to add up, skipped")
        return
    text = read(review)
    rows = re.findall(r"(?m)^\|\s*([^|]+?)\s*\|\s*\*{0,2}(\d+)\*{0,2}\s*\|(.*)\|\s*$", text)
    layers = [(name, int(n)) for name, n, tail in rows
              if "__" in tail and "—" not in tail
              and "总计" not in name and "层级" not in name]
    totals = [int(n) for name, n, tail in rows if "总计" in name]
    actual = len(re.findall(r"(?m)^### V\d+\.", strip_code_fences(read(slop))))
    if not layers or not totals:
        f.fail("layer-sum", "review 报告模板里找不到可相加的分层行或总计行")
        return
    s = sum(n for _, n in layers)
    problems = []
    if s != totals[0]:
        problems.append("分层行数相加是 %d，总计写 %d" % (s, totals[0]))
    if totals[0] != actual:
        problems.append("总计写 %d，但 slop-test.md 实有 %d 条" % (totals[0], actual))
    if problems:
        for p in problems:
            f.fail("layer-sum", p + " ｜ 分层：" + ", ".join("%s=%d" % (n, v) for n, v in layers))
    else:
        f.ok("layer-sum", "%d 层相加 = 总计 %d = slop-test 实际条数" % (len(layers), totals[0]))


def check_version_fields(root, f):
    """版本号只能有一个真值源：主 SKILL.md。

    子技能是主技能的组成部分，独立 version 字段只会制造漂移——历史上 9 个子技能
    的 version 长期停在 2.7.0，而主文件已是 2.9.0，没人发现。这里把它钉死：
    子技能 frontmatter 出现 version 即失败。

    同时要求主 SKILL.md、evals.json、README 徽章三处版本号一致——版本号一旦分叉，
    读文档的人和跑脚本的人会各说各话。
    """
    main_ver = None
    m = re.search(r"^version:\s*([0-9]+\.[0-9]+\.[0-9]+)\s*$", read(root / "SKILL.md"), re.M)
    if m:
        main_ver = m.group(1)

    bad = 0
    for sub in sorted((root / "subskills").glob("*/SKILL.md")):
        text = read(sub)
        sm = re.match(r"\A---\n(.*?)\n---\n", text, re.S)
        if not sm:
            continue
        vm = re.search(r"^version:\s*(.+)$", sm.group(1), re.M)
        if vm:
            f.fail("version-field", "subskills/%s/SKILL.md must not declare version "
                                    "(主 SKILL.md 是唯一真值源)，发现 version: %s"
                   % (sub.parent.name, vm.group(1).strip()))
            bad += 1
    if not bad:
        f.ok("version-field", "no subskill declares its own version")

    if not main_ver:
        f.fail("version-field", "SKILL.md frontmatter has no version: X.Y.Z")
        return

    evals_path = root / "evals" / "evals.json"
    if evals_path.exists():
        try:
            ev = json.loads(read(evals_path)).get("version")
        except (ValueError, OSError):
            ev = None
        if ev != main_ver:
            f.fail("version-field", "evals/evals.json version %r != SKILL.md version %r"
                   % (ev, main_ver))
            bad += 1
        else:
            f.ok("version-field", "evals.json version matches SKILL.md (%s)" % main_ver)

    readme = root / "README.md"
    if readme.exists():
        bm = re.search(r"badge/version-([0-9]+\.[0-9]+\.[0-9]+)", read(readme))
        if not bm:
            f.fail("version-field", "README.md has no version badge")
            bad += 1
        elif bm.group(1) != main_ver:
            f.fail("version-field", "README badge %r != SKILL.md version %r"
                   % (bm.group(1), main_ver))
            bad += 1
        else:
            f.ok("version-field", "README badge matches SKILL.md (%s)" % main_ver)


def main(argv=None):
    known = ("--skill-dir", "--json")
    for arg in argv or sys.argv[1:]:
        if arg.startswith("-") and arg not in known and not arg.startswith("--json="):
            sys.stderr.write("unknown flag %r (allowed: %s)\n" % (arg, ", ".join(known)))
            return 2

    ap = argparse.ArgumentParser(prog="audit_integrity.py", add_help=True)
    ap.add_argument("--skill-dir", default=str(Path(__file__).resolve().parent.parent))
    ap.add_argument("--json", action="store_true", help="emit machine-readable findings")
    ns = ap.parse_args(argv)

    root = Path(ns.skill_dir).resolve()
    if not (root / "SKILL.md").exists():
        sys.stderr.write("not a skill dir (no SKILL.md): %s\n" % root)
        return 2

    f = Findings()
    for fn in (check_paths, check_orphans, check_counts, check_denominators,
               check_subskill_claims, check_cross_claims, check_part_claims,
               check_index_numbers, check_index_completeness, check_fences,
               check_frontmatter, check_round_consistency, check_policy_consistency,
               check_gate_inventory, check_layer_sum, check_tools,
               check_version_fields):
        fn(root, f)

    if ns.json:
        print(json.dumps({"failures": f.items, "passed": f.passed},
                         ensure_ascii=False, indent=2))
    else:
        for item in f.items:
            print("FAIL  [%s] %s" % (item["check"], item["detail"]))
        print("-" * 60)
        print("findings=%d checks_passed=%d" % (len(f.items), len(f.passed)))
        print("RESULT: FAIL" if f.items else "RESULT: PASS")
    return 1 if f.items else 0


if __name__ == "__main__":
    sys.exit(main())
